GRANT CONNECT ON DATABASE :"database_name" TO theatre_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO theatre_app;

CREATE TABLE plays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    age_restriction INTEGER NOT NULL CHECK (age_restriction >= 0)
);

CREATE TABLE theatre_halls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
    seat_count INTEGER NOT NULL CHECK (seat_count > 0)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (length(trim(email)) > 0)
);

CREATE TABLE performances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    play_id BIGINT NOT NULL REFERENCES plays(id),
    hall_id BIGINT NOT NULL REFERENCES theatre_halls(id),
    starts_at TIMESTAMP NOT NULL,
    base_price NUMERIC(10, 2) NOT NULL CHECK (base_price >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED'))
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id BIGINT NOT NULL REFERENCES performances(id),
    seat_number INTEGER NOT NULL CHECK (seat_number > 0),
    user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('RESERVED', 'PURCHASED', 'CANCELLED', 'REFUNDED')),
    price_paid NUMERIC(10, 2),
    CONSTRAINT ck_tickets_paid_price CHECK (
        price_paid IS NULL OR (price_paid >= 0 AND status IN ('PURCHASED', 'REFUNDED'))
    ),
    CONSTRAINT ck_tickets_paid_status_price CHECK (
        status NOT IN ('PURCHASED', 'REFUNDED') OR price_paid IS NOT NULL
    )
);

CREATE INDEX performances_hall_status_starts_idx ON performances(hall_id, status, starts_at);
CREATE INDEX tickets_performance_idx ON tickets(performance_id);
CREATE INDEX tickets_user_idx ON tickets(user_id);
CREATE UNIQUE INDEX uk_ticket_performance_seat_active
    ON tickets(performance_id, seat_number)
    WHERE status IN ('RESERVED', 'PURCHASED');

